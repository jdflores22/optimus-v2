function genericLayout(label: string): DocumentLayout {
  return {
    canvas: defaultCanvas(),
    elements: [
      makeElement('header_banner', 1, {
        content: label,
        subtitle: 'Document Template',
        style: { textAlign: 'center', backgroundColor: '#1e3a5f', color: '#ffffff', fontSize: 20, padding: 20 },
      }),
      makeElement('text', 2, {
        content: 'Design your document by adding elements from the palette.',
        style: { textAlign: 'center', fontSize: 12, color: '#444444' },
      }),
    ],
  };
}

export function defaultDocumentLayout(documentType: string): DocumentLayout {
  if (documentType === 'EDO') return defaultEdoLayout();
  return genericLayout(documentType);
}

export function parseDocumentLayout(
  layoutJson: string | null | undefined,
  documentType: DocumentTemplateTypeId | string,
  paperSize: string,
  orientation: string,
): DocumentLayout {
  if (layoutJson) {
    try {
      const parsed = JSON.parse(layoutJson) as DocumentLayout;
      if (parsed.canvas && parsed.elements) return parsed;
    } catch {
      /* fall through */
    }
  }
  const layout = defaultDocumentLayout(documentType);
  layout.canvas.paperSize = paperSize || layout.canvas.paperSize;
  layout.canvas.orientation = orientation || layout.canvas.orientation;
  return layout;
}

export function serializeDocumentLayout(layout: DocumentLayout): string {
  return JSON.stringify(layout);
}

