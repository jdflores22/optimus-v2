type LayoutElement = Record<string, unknown>;
export type DocumentLayout = { canvas: Record<string, unknown>; elements: LayoutElement[] };

function elId() {
  return `el_${Math.random().toString(16).slice(2, 10)}`;
}

function makeElement(type: string, order: number, config: LayoutElement = {}): LayoutElement {
  return {
    id: elId(),
    type,
    order,
    content: '',
    placeholder: '',
    label: '',
    style: {
      fontSize: 12,
      fontWeight: 'normal',
      textAlign: 'left',
      color: '#000000',
      backgroundColor: 'transparent',
      padding: 0,
      marginTop: 0,
      marginRight: 0,
      marginBottom: 8,
      marginLeft: 0,
    },
    position: { x: 48, y: 48, width: 698 },
    config: {},
    ...config,
  };
}

